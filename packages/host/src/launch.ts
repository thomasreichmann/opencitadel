/**
 * Turns server.json into the dedicated-server command line and the generated cfg file.
 *
 * Secrets (rcon_password, sv_password) go into `citadel/cfg/opencitadel_server.cfg`, which the
 * command line `+exec`s, so they never appear in the process list.
 */

import { join } from 'node:path';
import type { GameLayout } from '@opencitadel/gamefiles';
import type { HostConfig } from './config.js';

export const CFG_NAME = 'opencitadel_server.cfg';

export interface LaunchPlan {
  command: string;
  args: string[];
  cwd: string;
  /** Extra environment for the server process (merged over the host's own). */
  env: Record<string, string>;
  cfgPath: string;
  cfgContents: string;
}

export interface BridgeEndpoint {
  port: number;
  token: string;
}

/**
 * Makes a value safe inside a double-quoted cfg token. Source cfg has no escape for `"`, and a
 * newline would end the command (letting a crafted hostname inject commands), so both go.
 */
export function cfgQuote(value: string): string {
  return `"${value.replace(/["\r\n\u0000-\u001f\u007f]/g, '')}"`;
}

export function buildServerCfg(config: HostConfig): string {
  const lines = [
    '// Generated by citadel-host on every start. Edit server.json instead; changes here are overwritten.',
    `hostname ${cfgQuote(config.name)}`,
    `sv_password ${cfgQuote(config.game.password)}`,
    `rcon_password ${cfgQuote(config.rcon.enabled ? config.rcon.password : '')}`,
  ];
  for (const [name, value] of Object.entries(config.game.convars)) {
    // Names are validated as [A-Za-z0-9_]+ by the config schema.
    lines.push(`${name} ${cfgQuote(value)}`);
  }
  return lines.join('\n') + '\n';
}

/** Flags passed to deadlock.exe / deadworks.exe (without the executable or wrapper). */
export function buildServerArgs(config: HostConfig): string[] {
  const g = config.game;
  const args = ['-dedicated', '-console', '-dev', '-insecure', '-allow_no_lobby_connect'];
  if (config.rcon.enabled && config.rcon.password) args.push('-usercon');
  if (g.logSource === 'condebug') args.push('-condebug');
  if (g.maxPlayers !== 12) args.push('-maxplayers', String(g.maxPlayers));
  args.push(
    '+tv_citadel_auto_record', '0',
    '+spec_replay_enable', '0',
    '+tv_enable', '0',
    '+citadel_upload_replay_enabled', '0',
    '+hostport', String(g.port),
    '+exec', CFG_NAME,
    ...g.extraArgs,
    // Last, so every setting above is in place before the map loads.
    '+map', g.map,
  );
  return args;
}

export function planLaunch(config: HostConfig, layout: GameLayout, bridge?: BridgeEndpoint): LaunchPlan {
  const exe = config.game.executable === 'deadworks' ? layout.deadworksExe : layout.exe;
  const flags = buildServerArgs(config);
  const [wrapperCmd, ...wrapperArgs] = config.game.wrapper;
  const env: Record<string, string> = {};
  if (bridge) {
    env.OPENCITADEL_BRIDGE = `127.0.0.1:${bridge.port}`;
    env.OPENCITADEL_BRIDGE_TOKEN = bridge.token;
  }
  return {
    command: wrapperCmd ?? exe,
    args: wrapperCmd ? [...wrapperArgs, exe, ...flags] : flags,
    cwd: layout.binDir,
    env,
    cfgPath: join(layout.citadelDir, 'cfg', CFG_NAME),
    cfgContents: buildServerCfg(config),
  };
}
